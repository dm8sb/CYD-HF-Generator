#include "frequency_utils.h"
#include <constants.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>

namespace FrequencyUtils {

uint64_t clamp(uint64_t hz) {
    if (hz < FREQ_MIN_HZ) return FREQ_MIN_HZ;
    if (hz > FREQ_MAX_HZ) return FREQ_MAX_HZ;
    return hz;
}

uint64_t applyCorrection(uint64_t hz, int32_t correctionPpmOrHz) {
    // The osmanovv library consumes correction directly. This helper is kept for display
    // and future validation. Correction is treated as ppm for small values and direct Hz
    // for large calibration offsets at 100 MHz.
    int64_t delta = 0;
    if (correctionPpmOrHz > -10000 && correctionPpmOrHz < 10000) {
        delta = (int64_t)((double)hz * ((double)correctionPpmOrHz / 1000000.0));
    } else {
        delta = correctionPpmOrHz;
    }
    int64_t corrected = (int64_t)hz + delta;
    return clamp(corrected > 0 ? (uint64_t)corrected : FREQ_MIN_HZ);
}

uint64_t nearestSi5351Hz(uint64_t hz) {
    hz = clamp(hz);

    // Approximate the actual frequency generated by osmanovv/esp32-si5351's
    // si5351_Calc() integer math. This keeps the GUI state closer to the actual
    // synthesized value instead of merely echoing the requested value.
    int32_t f = (int32_t)hz;
    const int32_t fxtal = 25000000;
    int32_t a = 0, b = 0, c = 1, x = 0, y = 0, z = 1, t = 1;

    if (f < 81000000) {
        a = 36; b = 0; c = 1;
        const int32_t fpll = 900000000;
        x = fpll / f;
        t = (f >> 20) + 1;
        y = (fpll % f) / t;
        z = f / t;
    } else {
        if (f >= 150000000) x = 4;
        else if (f >= 100000000) x = 6;
        else x = 8;
        y = 0; z = 1;
        int32_t numerator = x * f;
        a = numerator / fxtal;
        t = (fxtal >> 20) + 1;
        b = (numerator % fxtal) / t;
        c = fxtal / t;
    }

    double pll = (double)fxtal * ((double)a + ((double)b / (double)c));
    double div = (double)x + ((double)y / (double)z);
    if (div <= 0.0) return hz;
    uint64_t actual = (uint64_t)llround(pll / div);
    return clamp(actual);
}

void format(uint64_t hz, char* out, size_t outSize) {
    if (!out || outSize == 0) return;

    // HF generator range is 1-100 MHz. Display as MHz with grouped
    // fractional Hz digits: 1.000 000 MHz, 10.700 000 MHz, 100.000 000 MHz.
    uint64_t wholeMHz = hz / 1000000ULL;
    uint64_t fracHz = hz % 1000000ULL;
    uint64_t fracK = fracHz / 1000ULL;
    uint64_t fracR = fracHz % 1000ULL;
    snprintf(out, outSize, "%llu.%03llu %03llu MHz",
             (unsigned long long)wholeMHz,
             (unsigned long long)fracK,
             (unsigned long long)fracR);
}

bool parseFrequency(const char* text, const char* unit, uint64_t* outHz) {
    if (!text || !outHz) return false;
    char* end = nullptr;
    double v = strtod(text, &end);
    if (end == text || v <= 0) return false;
    double scale = 1.0;
    if (unit) {
        if (strcmp(unit, "kHz") == 0) scale = 1000.0;
        else if (strcmp(unit, "MHz") == 0) scale = 1000000.0;
        else scale = 1.0;
    }
    double hz = v * scale;
    if (hz < 0.0 || hz > 1000000000000.0) return false;
    *outHz = nearestSi5351Hz((uint64_t)(hz + 0.5));
    return true;
}

}
