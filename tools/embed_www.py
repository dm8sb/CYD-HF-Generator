# PlatformIO pre-script (S55): embeds the web interface data/www into the firmware, so one image
# holds everything (no LittleFS partition; the web flasher G2 writes a single app).
# - app.js and style.css: gzip -9 (mtime 0, reproducible), served with Content-Encoding: gzip and
#   an ETag (first 16 hex digits of their SHA-256).
# - index.html: as text, because the server puts the per-boot token into its {{TOKEN}}
#   placeholder (net/web_server.cpp). {{SRC_REF}} (footer links) is replaced here with the
#   release tag of the build (source_ref()).
# - README.md is documentation only and is not embedded.
# The result goes to $BUILD_DIR/www/www_assets.h (only included by net/web_server.cpp) and is
# rewritten only when it changes, so a normal build does not recompile anything.
import gzip
import hashlib
import io
import os
import re
import subprocess

Import("env")

REF_RE = re.compile(r"^v[0-9A-Za-z.+-]{1,63}$")


def source_ref():
    """Git ref the footer links to (AF30, E-39): the release tag of this build, so the source
    and license links match the firmware. The tag pushed in the release workflow, else a v* tag
    on HEAD, else v<APP_VERSION> (the release a development build leads to). Never the commit:
    the page is readable without login (S-26). Changes only with the tag, so a normal build
    does not rewrite www_assets.h."""
    candidates = []
    if os.environ.get("GITHUB_REF_TYPE") == "tag":
        candidates.append(os.environ.get("GITHUB_REF_NAME", ""))
    try:
        out = subprocess.check_output(["git", "describe", "--exact-match", "--tags", "--match", "v*", "HEAD"],
                                      cwd=env.subst("$PROJECT_DIR"), stderr=subprocess.DEVNULL)
        candidates.append(out.decode("utf-8", "replace").strip())
    except Exception:
        pass
    with open(os.path.join(env.subst("$PROJECT_DIR"), "include", "config.h"), "r", encoding="utf-8") as f:
        m = re.search(r'#define APP_VERSION "([^"]+)"', f.read())
    if not m:
        raise Exception("include/config.h: APP_VERSION missing")
    candidates.append("v" + m.group(1))
    return next(c for c in candidates if REF_RE.match(c))

FILES = [
    # (file, C name, content type, gzip)
    ("index.html", "INDEX_HTML", "text/html; charset=utf-8", False),
    ("app.js", "APP_JS", "text/javascript; charset=utf-8", True),
    ("style.css", "STYLE_CSS", "text/css; charset=utf-8", True),
]


def gz(data):
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def c_array(name, data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(data), "\n".join(lines))


def generate():
    src = os.path.join(env.subst("$PROJECT_DIR"), "data", "www")
    out_dir = os.path.join(env.subst("$BUILD_DIR"), "www")
    parts = [
        "// Generated by tools/embed_www.py from data/www; do not edit.\n",
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n",
        "struct WwwAsset {\n    const char* path;\n    const uint8_t* data;\n    size_t size;\n"
        "    const char* type;\n    bool gzip;\n    const char* etag;\n};\n\n",
    ]
    table = []
    total_raw = total = 0
    ref = source_ref()
    for name, cname, ctype, compress in FILES:
        with open(os.path.join(src, name), "rb") as f:
            raw = f.read()
        if name == "index.html":
            if b"{{TOKEN}}" not in raw or b"{{SRC_REF}}" not in raw:
                raise Exception("data/www/index.html: {{TOKEN}} or {{SRC_REF}} placeholder missing")
            raw = raw.replace(b"{{SRC_REF}}", ref.encode("ascii"))
        data = gz(raw) if compress else raw
        etag = '"%s"' % hashlib.sha256(data).hexdigest()[:16]
        parts.append(c_array("WWW_" + cname, data))
        table.append('    {"/%s", WWW_%s, sizeof(WWW_%s), "%s", %s, "\\"%s\\""},' %
                     (name, cname, cname, ctype, "true" if compress else "false", etag.strip('"')))
        total_raw += len(raw)
        total += len(data)
    parts.append("\nstatic const WwwAsset WWW_ASSETS[] = {\n%s\n};\n" % "\n".join(table))
    text = "".join(parts)
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "www_assets.h")
    old = None
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("embed_www: %d B of data/www embedded as %d B" % (total_raw, total))
    return out_dir


env.Append(CPPPATH=[generate()])
